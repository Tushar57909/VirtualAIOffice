import React, { useState } from 'react';
import { 
  Download, Copy, CheckCircle, FileText, 
  Clock, Users, Cpu, Sparkles, Code 
} from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

interface ReportPanelProps {
  response: string;
  onBuildPrototype: () => void;
  taskTitle?: string;
}

const ReportPanel: React.FC<ReportPanelProps> = ({ 
  response, 
  onBuildPrototype, 
  taskTitle = "Engineering Analysis & Architecture Synthesis" 
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    navigator.clipboard.writeText(response);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleExport = () => {
    const element = document.createElement("a");
    const file = new Blob([response], { type: 'text/markdown' });
    element.href = URL.createObjectURL(file);
    element.download = "ai_office_engineering_report.md";
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div className="bg-white border border-slate-200 rounded-3xl shadow-xl overflow-hidden flex flex-col flex-1 min-h-[600px] font-sans">
      {/* Document Top Header Bar */}
      <div className="p-6 border-b border-slate-100 bg-slate-50/60 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div className="flex items-start gap-3.5">
          <div className="w-10 h-10 rounded-2xl bg-indigo-50 border border-indigo-200 flex items-center justify-center text-indigo-600 shrink-0 shadow-xs">
            <FileText className="w-5 h-5" />
          </div>
          <div>
            <div className="flex items-center gap-1.5 text-xs font-semibold text-indigo-600 uppercase tracking-wider mb-0.5">
              <Sparkles className="w-3.5 h-3.5 text-indigo-600" />
              <span>Project Analysis Document</span>
            </div>
            <h2 className="text-lg sm:text-xl font-bold text-slate-900 tracking-tight">
              {taskTitle}
            </h2>
          </div>
        </div>

        {/* Action Buttons */}
        <div className="flex items-center gap-3 flex-wrap">
          <button 
            onClick={onBuildPrototype}
            className="inline-flex items-center gap-2 px-5 py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-xs font-semibold transition-all shadow-lg shadow-indigo-500/25 active:scale-98"
          >
            <Code className="w-4 h-4 text-white" />
            <span>Build Frontend Prototype</span>
          </button>

          <div className="h-6 w-px bg-slate-200 hidden sm:block mx-1"></div>

          <button 
            onClick={handleCopy} 
            className="inline-flex items-center gap-1.5 px-3.5 py-2 bg-white border border-slate-200 hover:bg-slate-50 text-slate-700 rounded-xl text-xs font-semibold transition-all shadow-xs" 
            title="Copy Report"
          >
            {copied ? <CheckCircle className="w-4 h-4 text-emerald-600" /> : <Copy className="w-4 h-4 text-slate-400" />}
            <span>{copied ? 'Copied' : 'Copy'}</span>
          </button>

          <button 
            onClick={handleExport}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 bg-white border border-slate-200 hover:bg-slate-50 text-slate-700 rounded-xl text-xs font-semibold transition-all shadow-xs" 
            title="Export Markdown"
          >
            <Download className="w-4 h-4 text-slate-400" />
            <span>Export</span>
          </button>
        </div>
      </div>

      {/* Document Metadata Strip */}
      <div className="px-6 py-3 bg-slate-50 border-b border-slate-100 flex flex-wrap items-center gap-4 text-xs font-medium text-slate-600">
        <div className="flex items-center gap-2 px-2.5 py-1 rounded-lg bg-white border border-slate-200 text-slate-800">
          <Cpu className="w-3.5 h-3.5 text-indigo-600" />
          <span>Generated by AI Office</span>
        </div>
        <div className="flex items-center gap-2 px-2.5 py-1 rounded-lg bg-white border border-slate-200 text-slate-800">
          <Users className="w-3.5 h-3.5 text-purple-600" />
          <span>6 Agents Involved</span>
        </div>
        <div className="flex items-center gap-2 px-2.5 py-1 rounded-lg bg-emerald-50 border border-emerald-200 text-emerald-700 font-semibold">
          <CheckCircle className="w-3.5 h-3.5 text-emerald-600" />
          <span>Status: Completed</span>
        </div>
        <div className="flex items-center gap-2 text-slate-500">
          <Clock className="w-3.5 h-3.5 text-slate-400" />
          <span>Execution Time: Synchronous</span>
        </div>
      </div>

      {/* Document Content Area */}
      <div className="flex-1 p-6 lg:p-10 overflow-y-auto custom-scrollbar bg-white">
        <article className="max-w-4xl mx-auto prose prose-slate prose-headings:font-bold prose-headings:text-slate-900 prose-headings:tracking-tight prose-h1:text-xl prose-h2:text-base prose-h2:border-b prose-h2:border-slate-200 prose-h2:pb-2.5 prose-h2:mt-8 prose-p:text-slate-700 prose-p:text-sm prose-p:leading-relaxed prose-li:text-slate-700 prose-li:text-sm prose-code:text-indigo-600 prose-code:bg-slate-100 prose-code:px-2 prose-code:py-0.5 prose-code:rounded-md prose-code:font-mono prose-code:before:content-none prose-code:after:content-none prose-pre:bg-slate-900 prose-pre:text-slate-100 prose-pre:border prose-pre:border-slate-800 prose-pre:rounded-2xl shadow-md">
          <ReactMarkdown remarkPlugins={[remarkGfm]}>
            {response}
          </ReactMarkdown>
        </article>
      </div>
    </div>
  );
};

export default ReportPanel;
